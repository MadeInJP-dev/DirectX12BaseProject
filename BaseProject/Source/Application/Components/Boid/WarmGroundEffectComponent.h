#pragma once

namespace App::Component
{
	//==========================================================================================
	// WarmGroundEffectComponent
	//
	// 砂漠でワームの体(小隊長)が地面の近く・地面の中に居るときに、地表へ砂埃を炊くための状態
	//
	// ・付けるのは SwarmBossController(小隊長の生成時)。プレハブには入れない。
	//   ボイド1体ずつには付けない(4000体ぶんのレイとエフェクトは重く、細かい砂埃が散らばって見えるため)。
	// ・持つのは次に炊くまでの残り時間だけ。どのエフェクトをどう出すかは
	//   WormGroundEffectResource(SwarmBossController が書く)にまとめてあり、小隊長全員で共有する。
	// ・レイを打ってエフェクトを出すのは BoidGroundEffectSystem。
	//   残り時間が切れた小隊長だけがレイを打つ。生成時にばらしておくので、全員が同じフレームに揃わない。
	// ・実行中の値だけなので保存しない。
	//==========================================================================================
	struct WarmGroundEffectComponent
	{
		float timer = 0.0f;		// 次に炊くまでの残り時間(秒)
	};
}
