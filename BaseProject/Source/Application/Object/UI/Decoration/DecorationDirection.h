#pragma once

#include "Application/AppCommon.h"

//==========================================================================================
// 飾りの方向
//
// 旧 Decoration(Decoration.h)と新しいエレメント(UIDecorationElementBase.h)の両方が使うので、
// どちらにも置かずにここへ分けてある(両方を読む翻訳単位で二重定義にならないように)
//==========================================================================================
namespace App::Object::Decoration
{
	//======================================================================================
	// 方向 : 枠をどの辺に出すか
	//======================================================================================
	enum class EDirection : uint32_t
	{
		NONE	= 0,
		UP		= 1 << 0,
		DOWN	= 1 << 1,
		LEFT	= 1 << 2,
		RIGHT	= 1 << 3,

		ALL		= UP | DOWN | LEFT | RIGHT,
	};
	ENUM_ATTR_BITFLAG(EDirection);
}
