#pragma once

#include "Application/AppCommon.h"

namespace App::Object::Decoration
{
	//======================================================================================
	// ボディの形
	//
	// ※ 値は保存される。増やすときは末尾へ
	//======================================================================================
	enum class EHitShape : uint32_t
	{
		Rect,		// エレメントの矩形そのもの
		Ellipse,	// エレメントの矩形に内接する楕円(正方形なら円)
	};

	//======================================================================================
	// 当たり判定のボディ : エレメントが任意で1つ持つ
	//
	// 形はエレメントの置き場所(位置・大きさ・ピボット・回転)にそのまま乗る。
	// 持ち主の UI はカーソルの位置を渡して「当たったか」だけを受け取る(UIDecoration::IsHit)。
	// 判定を受けるかどうかは UI 側(UIBase::IsHitTarget)が決める
	//======================================================================================
	struct UIHitBody
	{
		EHitShape shape = EHitShape::Rect;		// 形
		Math::Vector2 padding = {};				// 余白(px)。見た目より広く/狭く(負)取りたいとき用

		/// <summary>アニメーション・反応で変わった今の形も当たりに入れるか</summary>
		/// <remarks>
		/// 今の形だけに差し替えず、素の形と合わせた範囲で当てる。
		/// 乗ると縮む反応を付けたときに「乗る→縮んで外れる→戻って乗る」が毎フレーム入れ替わらないように
		/// </remarks>
		bool isFollowAnim = false;

		/// <summary>エレメントの矩形ではなく、親(UI)の矩形に当てるか</summary>
		/// <remarks>
		/// 親の大きさ(UIAnchor::pixelSize)・ピボット・回転をそのまま使う。
		/// 並べる側が毎フレーム親の大きさを入れ直す UI(設定画面の行・スクロールバー)でも、判定が追従する
		/// </remarks>
		bool isUseParentRect = false;
	};
}
