#pragma once

namespace App::InstanceResource
{
	//==========================================================================================
	//
	// 画面のラジアルブラーを震わせる依頼(ボスの咆哮など)。
	//
	// 頼む側(今は SwarmBossController)が毎フレーム強さ(weight)と見た目の調整値を書き、
	// RadialBlurShakeSystem がカメラの RadialBlurComponent へ震えを足す。
	// カメラは頼む側から見えない(どのカメラで映すかはシステム側が決める)ので、間にこれを挟む。
	//
	// ・頼むのをやめるときは weight を 0 に戻す。書きっぱなしにすると震えが残り続ける。
	// ・頼む側は1つの想定。複数が書くと最後に書いたものが勝つ。
	// ・カメラのブラーを切っていても(RadialBlurComponent.enable = false)、震えている間は掛かる。
	//
	//==========================================================================================
	struct RadialBlurShakeResource
	{
		// 震えの強さ(0〜1)。下の各値にそのまま掛かる。0 なら何もしない
		float weight = 0.0f;

		//--------------------------------------------------------------------------
		// 見た目の調整値(weight = 1 のとき)
		//--------------------------------------------------------------------------
		float strength       = 0.15f;	// 引きずり量(UV単位)。カメラの速度ぶんの量に足す
		float strengthJitter = 0.5f;	// 引きずり量の揺れ幅(strength に対する割合。0〜1)
		float centerJitter   = 0.02f;	// ブラーの中心を揺らす幅(UV単位)
		float frequency      = 18.0f;	// 揺れの速さ(回/秒)

		void Clear()
		{
			weight = 0.0f;
		}
	};
}
