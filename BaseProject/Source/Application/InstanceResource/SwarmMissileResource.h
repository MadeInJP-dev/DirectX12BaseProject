#pragma once

namespace App::InstanceResource
{
	//==========================================================================================
	//
	// ワームの体から切り離す自爆ミサイルの、切り離しの要求と飛び方の調整値。
	//
	// 書くのはワームボスの巻き付き攻撃(SwarmBossCoilAttackState)と円陣ミサイル(SwarmBossFormationAttackState)。
	//   ・launchRequests … 「この小隊長からボイドを1体切り離せ」という要求(小隊長のエンティティ)
	//   ・ringCenter     … 巻いている輪の中心。切り離した直後は輪の外側へ飛び出させる
	//   ・調整値         … 攻撃中は毎フレーム書き写す。攻撃が終わった後も飛んでいるものは
	//                      最後に書かれた値で飛び続ける
	// 受けるのは SwarmMissileSystem。
	//   ・切り離し : 要求された小隊長のボイドを1体探し、群れの部品を外してミサイルにする
	//               (処理した要求はそのフレームで捨てる。ボイドが残っていなければ何もしない)
	//   ・飛行     : 打ち上げ → 誘導(曲がれる角度に上限あり)
	//   ・自爆     : プレイヤーに近づくか、時間切れで自分を落とす
	// 間にこのリソースを挟んでいるのはウェーブ(WormWaveResource)と同じ理由で、
	// オブジェクト側の更新で 4000 体を走査するとチャンク単位で回れないため。
	//
	// プレイヤーの形(カプセル)は SwarmContactDamageResource のものを使う(書くのは SwarmBossController)。
	//
	//==========================================================================================
	struct SwarmMissileResource
	{
		//--------------------------------------------------------------------------
		// 切り離しの要求(CoilAttack が積み、SwarmMissileSystem が処理して捨てる)
		//--------------------------------------------------------------------------
		std::vector<Engine::ECS::Entity> launchRequests = {};	// ボイドを1体切り離す小隊長
		Math::Vector3 ringCenter = {};							// 巻いている輪の中心(ワールド)

		//--------------------------------------------------------------------------
		// 打ち上げ : 切り離した直後は輪の外側・上へ飛び出す(誘導しない)
		//--------------------------------------------------------------------------
		float launchSpeed  = 40.0f;		// 打ち上げの速さ(m/秒)
		float launchTime   = 0.4f;		// 打ち上げの長さ(秒)。過ぎたら誘導を始める
		float launchUp     = 1.0f;		// 打ち上げの向きの上向きの重み
		float launchOut    = 0.5f;		// 打ち上げの向きの外向き(輪の中心から離れる向き)の重み
		float launchSpread = 0.3f;		// 打ち上げの向きのばらつき(0で揃う)

		// 打ち上げの向きに混ぜる、決まった向き(円陣ミサイルはプレイヤーの方)。巻き付きは重み 0
		Math::Vector3 launchForwardDir = { 0.0f, 0.0f, 1.0f };	// 決まった向き(単位ベクトル)
		float launchForward = 0.0f;								// その重み

		//--------------------------------------------------------------------------
		// 誘導 : 曲がれる角度に上限があるので、横へ大きく動けば避けられる
		//--------------------------------------------------------------------------
		float speed        = 80.0f;		// 誘導中の最高速(m/秒)
		float acceleration = 80.0f;		// 打ち上げの速さから最高速へ上げる加速度(m/秒^2)
		float turnSpeedDeg = 120.0f;	// 1秒あたりに曲がれる角度(度/秒)
		float lifeTime     = 6.0f;		// 切り離してからこの時間で自爆する(秒。外れたもの)

		//--------------------------------------------------------------------------
		// 自爆
		//--------------------------------------------------------------------------
		float explodeRadius = 3.0f;		// プレイヤーのカプセルとこの距離まで近づいたら自爆する(m)
		float damage        = 10.0f;	// 自爆が当たったときのダメージ

		//--------------------------------------------------------------------------
		// 見た目 : 切り離した瞬間に発光を差し替える(ウェーブはもう走らない)
		//--------------------------------------------------------------------------
		Math::Vector3 color = { 1.0f, 0.15f, 0.05f };	// 発光色(0〜1)
		float intensity = 10.0f;						// 発光の強さ

		void Reserve(size_t a_size) { launchRequests.reserve(a_size); }
	};
}
