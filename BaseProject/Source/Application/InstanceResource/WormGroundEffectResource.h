#pragma once

namespace App::InstanceResource
{
	//==========================================================================================
	//
	// ワームの体(小隊長)が地面の近く・地面の中で炊く砂埃の設定。
	//
	// 出すのは SwarmBossController(どのエフェクトをどう出すかの調整値を持つ)。
	// 受けて小隊長ぶんのレイを打ち、エフェクトを出すのは BoidGroundEffectSystem。
	// 間にこのリソースを挟んでいるのはウェーブ(WormWaveResource)と同じ理由で、
	// オブジェクト側の更新で ECS を全走査するとチャンク単位で回れないため。
	//
	//   地面の上 … 真下の地面までの距離が maxHeight 以内なら、近いほど大きく炊く
	//   地面の中 … 真上の地表へ、深さに関係なく常に炊く
	//
	// 炊くのはボイド1体ずつではなく小隊長ごと(ボイドが 4000 体だとレイもエフェクトも多すぎるため)。
	// 小隊長は体の芯に一列に並んでいるので、そのまま炊くと同じ大きさの玉が連なって見える。
	// そうならないよう、炊く位置を体の太さの中へ横にばらし(scatterRadius)、大きさもばらす(scaleJitter)。
	//
	// 1回炊くたびにエフェクトのエンティティが1体増えるので、数は2段で抑える。
	//   ・1体ごとの間隔(interval)。間隔が来た小隊長だけがレイを打つので、レイの本数も減る
	//   ・1フレームに出す上限(maxSpawnPerFrame)。全身が潜っても出る数が跳ねない
	//
	//==========================================================================================
	struct WormGroundEffectResource
	{
		//--------------------------------------------------------------------------
		// 調整値(SwarmBossController が毎フレーム書き写す)
		//--------------------------------------------------------------------------
		Core::GUID effectGUID = Core::DEFAULT_GUID;	// 炊くエフェクト(出し切って消える単発のもの)

		float maxHeight   = 20.0f;		// 地面からこの高さまでの小隊長が炊く(m)
		float maxDepth    = 150.0f;		// 地表からこの深さまでの小隊長が炊く(真上へ打つレイの長さ。m)
		float nearScale   = 1.0f;		// 地表すれすれでの大きさ
		float farScale    = 0.3f;		// maxHeight ぎりぎりでの大きさ
		float underScale  = 1.0f;		// 地面の中に居るときの大きさ
		float interval    = 0.5f;		// 1体が炊く間隔(秒。実際は ±30% ばらす。砂埃が薄れるより短くして途切れないようにする)
		float scatterRadius = 4.0f;		// 炊く位置を小隊長から水平にばらす半径(m)
		float scaleJitter   = 0.3f;		// 大きさを ±この割合でばらす
		uint32_t maxSpawnPerFrame = 16;	// 1フレームに出す上限

		// ボスが居て炊く設定になっているか。false の間は BoidGroundEffectSystem が何もしない
		bool isActive = false;

		//--------------------------------------------------------------------------
		// 実行中の状態
		//--------------------------------------------------------------------------
		uint32_t spawnedThisFrame = 0;	// 今フレームに出した数(SwarmBossController が毎フレーム0に戻す)

		void Clear()
		{
			isActive = false;
			spawnedThisFrame = 0;
		}
	};
}
