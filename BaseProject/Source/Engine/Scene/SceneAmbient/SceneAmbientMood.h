#pragma once

namespace Engine::Scene
{
	//======================================================================================
	// 環境設定に掛ける演出(ボスの死亡で暗くしてフォグを濃くする、など)
	//
	// シーンの値(SceneAmbient)は書き換えず、流し込むときに混ぜるだけ(保存もされない)。
	// 頼む側は SceneManager::RequestAmbientMood で毎フレーム頼む。
	// 頼まなかったフレームはシーンの値のまま流れる。
	//
	// weight で「シーンの値 → ここの値」へ寄せる(0 : シーンの値のまま / 1 : ここの値)
	//======================================================================================
	struct SceneAmbientMood
	{
		float weight = 0.0f;				// 掛かり具合(0〜1)

		// 明るさの倍率 : 環境光・平行光・空・高さ/距離フォグの色に掛ける(1 でそのまま)。
		// フォグに届く光(環境光・平行光)も一緒に暗くなる
		float lightScale = 1.0f;

		// ボリュメトリックフォグ(シーンのフォグ)の濃さ(1m あたり)と、メインカラーへ重ねる強さ。
		// 寄せる先の値。負なら寄せない(シーンの値のまま)
		float fogDensity = -1.0f;
		float fogCompositeIntensity = -1.0f;
	};
}
