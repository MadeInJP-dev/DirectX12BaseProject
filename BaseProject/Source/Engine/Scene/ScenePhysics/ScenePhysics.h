#pragma once

namespace Engine::Physics
{
	class PhysicsWorld;
}

namespace Engine::Scene
{
	//======================================================================================
	// シーンの物理の設定
	//
	// 重力などの物理の取り決めを、シーン(BaseScene)の持ち物として持つ。
	// シーンと一緒に保存される(シーンファイルの "Physics" グループ)。
	//
	// ・流し込む先は、そのシーンのワールドの PhysicsWorld(ECS のリソース)。
	//   自前で落下を解くシステム(DeathMotion / Ballistic など)は PhysicsWorld::GetGravity で引く。
	// ・値の実体は保存側(ここ)。読み込んだ後とエディターで動かした後に流し込む。
	//   保存されていないシーンは既定値(下向き 9.81 m/秒^2)のまま流し込まれる
	//======================================================================================
	class ScenePhysics
	{
	public:

		ScenePhysics() = default;
		~ScenePhysics() = default;
		NON_COPYABLE_NON_MOVABLE(ScenePhysics);

		//----------------------------------------------------------------------------------
		// 流し込む先(BaseScene の Enter / Exit から呼ぶ)
		//----------------------------------------------------------------------------------
		// a_pPhysicsWorld : シーンのワールドが持つ物理空間(借り物)。登録した時点の値を流し込む
		void Register(Physics::PhysicsWorld* a_pPhysicsWorld);
		void Unregister();

		//----------------------------------------------------------------------------------
		// 保存・読み込み : 読み込んだら流し込む
		//----------------------------------------------------------------------------------
		void Archive(Persistence::Archive& a_ar);

		//----------------------------------------------------------------------------------
		// 編集UI(エディターの SceneAmbientPanel から呼ばれる)。動かした瞬間に効く
		//----------------------------------------------------------------------------------
		void DrawEdit();

		const Math::Vector3& GetGravity() const { return m_gravity; }

	private:

		// 物理空間へ流し込む
		void Apply();

	private:

		//-------------------------------------------------------------------
		// 設定(保存される)
		//-------------------------------------------------------------------
		Math::Vector3 m_gravity = { 0.0f, -9.81f, 0.0f };	// 重力(m/秒^2)

		//-------------------------------------------------------------------
		// 状態(保存しない)
		//-------------------------------------------------------------------
		// 流し込む先(借り物) : 持ち主はシーンのワールド。ワールドより先に Unregister する
		Physics::PhysicsWorld* m_pPhysicsWorld = nullptr;
	};
}
