#pragma once

namespace Engine::Resource
{
	//==========================================================================================
	// UIプリセット : UI の飾り1つぶんの見た目の設計図
	//
	// 飾り(枠・画像・文字)から指されて、見た目・大きさ・反応・アニメを配る。
	// 指している飾りは、中身が変わるたびに写し直すので、プリセットを直せば使っている飾りが全部変わる。
	//
	// ・飾りの型は App 側(App::Object::Decoration)にあり、エンジンは中身を知らない。
	//   ここでは App が書いた飾り1つぶんの JSON を、文字列のまま預かるだけ。
	//   読み書きと、どこを写すかは App が決める(Decoration/DecorationPreset.h)
	// ・revision は中身が変わったことを知らせる番号。読み込んだとき・書き換えたときに
	//   アプリ全体で一意な値へ進むので、読み直しても「前と同じ番号」にはならない
	//==========================================================================================
	struct UIPreset
	{
		UIPreset() { Touch(); }
		explicit UIPreset(const std::string& a_name) : name(a_name) { Touch(); }
		~UIPreset() = default;
		NON_COPYABLE_MOVABLE(UIPreset);

		//---------------------------------------
		// 設定(保存される)
		//---------------------------------------
		std::string name = "";

		// 飾り1つぶん(App が書いた JSON の文字列)。空なら既定の飾りとして扱われる
		std::string decorationJson = "";

		//---------------------------------------
		// ランタイム(保存しない)
		//---------------------------------------

		// 中身が変わったことを知らせる番号。書き換えたら Touch で進める
		uint32_t revision = 0;

		// 書き換えてからまだ保存していないか(エディターの表示用)
		bool isDirty = false;

		//---------------------------------------
		// 操作
		//---------------------------------------

		// アーカイブ。フィールドを足すときは必ず末尾へ(.ob* は並び順で読むため)
		void Archive(Persistence::Archive& a_ar);

		// 拡張子なしのベースパスへ保存する
		void Save(const std::string& a_baseFilePath);

		// 中身を差し替える : 番号を進め、未保存にする
		void SetDecorationJson(const std::string& a_json);

		// 番号を進める(指している飾りが写し直す)
		void Touch();
	};
}
